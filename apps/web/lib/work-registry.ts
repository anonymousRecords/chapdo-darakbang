import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { readPosts } from "./post-loader";

export function generateWorkRegistry({
  directory,
  output,
  interactionIds,
  includeUnpublished = false,
  today,
}: {
  directory: string;
  output: string;
  interactionIds: readonly string[];
  includeUnpublished?: boolean;
  today?: string;
}) {
  const posts = readPosts({
    directory,
    interactionIds,
    includeUnpublished,
    today,
  });
  const native = posts.filter((post) => post.renderer === "react");
  const fingerprint = createHash("sha256")
    .update(JSON.stringify(posts))
    .digest("hex")
    .slice(0, 12);
  const entries = native
    .map(
      (post) =>
        `  ${JSON.stringify(post.slug)}: dynamic(() => import("../works/${post.slug}/Artwork"), { ssr: false, loading: () => <p role="status">작품을 불러오는 중…</p> }),`,
    )
    .join("\n");
  const source = `// Generated by pnpm gen:works; do not edit. ${fingerprint}
"use client";
import dynamic from "next/dynamic";
import type { ComponentType } from "react";
export const nativeWorks: Record<string, ComponentType> = {
${entries}
};
`;
  mkdirSync(dirname(output), { recursive: true });
  if (!existsSync(output) || readFileSync(output, "utf8") !== source)
    writeFileSync(output, source);
  return native.map((post) => post.slug);
}
